#!/usr/bin/env python3
"""Writes a theme's data.rml: the view models, sample instances and icon assets.

Each theme (themes/<name>/scene.rml) is hand-written; only this repetitive
sample data is generated, and every theme shares it, so the Android host can
drive any of them the same way. Only the font differs (themes/<name>/font).

    python3 tools/gen_data.py themes/retro      # usually via tools/build.py
"""
import sys
from pathlib import Path

theme = Path(sys.argv[1] if len(sys.argv) > 1 else ".")
font = (theme / "font").read_text().strip() if (theme / "font").exists() else "Inter.ttf"

FAVS = [("Movies", "movies"), ("Shows", "shows"), ("Spotify", "spotify")]
APPS = [
    ("Photos", "photos"), ("Games", "games"), ("FX", "browser"),
    ("Podcasts", "podcasts"), ("Radio", "radio"), ("Play Store", "store"),
    ("News", "news"), ("Weather", "weather"), ("Sports", "sports"),
    ("Kids", "kids"), ("Files", "files"), ("Arcade", "arcade"),
]
import os
if os.environ.get("MANY"):  # stress sample for scrolling: 3x the apps
    APPS = [(f"{l} {n}" if n else l, k) for n in ("", 2, 3) for l, k in APPS]
FOCUSED_FAV = 1  # Shows, so the preview shows one focused tile

icons = sorted({k for _, k in FAVS + APPS})
asset_id = {k: f"6:{10 + i}" for i, k in enumerate(icons)}

out = ['<Rive version="1" kind="fragment">', '    <!-- generated by tools/gen_data.py -->']
out.append(f'    <FontAsset file="fonts/{font}" name="{Path(font).stem}" id="6:1"/>')
out.append('    <ImageAsset file="art/nowplaying.png" name="nowplaying" id="6:2"/>')
for k in icons:
    out.append(f'    <ImageAsset file="icons/{k}.png" name="{k}" id="{asset_id[k]}"/>')


def tile_vm(name, vm, p_label, p_icon, p_focus, items, base, focused_index):
    out.append(f'    <ViewModel defaultInstanceId="{base}0" name="{name}" id="{vm}">')
    out.append(f'        <ViewModelPropertyString name="label" id="{p_label}"/>')
    out.append(f'        <ViewModelPropertyAssetImage name="icon" id="{p_icon}"/>')
    out.append(f'        <ViewModelPropertyBoolean name="focused" id="{p_focus}"/>')
    ids = []
    for i, (label, key) in enumerate(items):
        iid = f"{base}{i}"
        ids.append(iid)
        out.append(f'        <ViewModelInstance exports="true" name="{label}" id="{iid}">')
        out.append(f'            <ViewModelInstanceString propertyValue="{label}" viewModelPropertyId="{p_label}"/>')
        out.append(f'            <ViewModelInstanceAssetImage propertyValue="{asset_id[key]}" viewModelPropertyId="{p_icon}"/>')
        out.append(f'            <ViewModelInstanceBoolean propertyValue="{"true" if i == focused_index else "false"}" viewModelPropertyId="{p_focus}"/>')
        out.append('        </ViewModelInstance>')
    out.append('    </ViewModel>')
    return ids


fav_ids = tile_vm("FavTile", "4:20", "4:21", "4:22", "4:23", FAVS, "5:20", FOCUSED_FAV)
app_ids = tile_vm("AppTile", "4:10", "4:11", "4:12", "4:13", APPS, "5:1", -1)

out.append('''    <ViewModel defaultInstanceId="5:1" name="Home" id="4:1">
        <ViewModelPropertyString name="time" id="4:2"/>
        <ViewModelPropertyString name="date" id="4:3"/>
        <ViewModelPropertyString name="npTitle" id="4:4"/>
        <ViewModelPropertyString name="npSubtitle" id="4:5"/>
        <ViewModelPropertyAssetImage name="npArt" id="4:6"/>
        <ViewModelPropertyBoolean name="npPlaying" id="4:7"/>
        <ViewModelPropertyList name="favourites" id="4:8"/>
        <ViewModelPropertyList name="apps" id="4:9"/>
        <ViewModelPropertyBoolean name="screensaverFocused" id="4:30"/>
        <ViewModelPropertyBoolean name="settingsFocused" id="4:31"/>
        <ViewModelPropertyBoolean name="prevFocused" id="4:34"/>
        <ViewModelPropertyBoolean name="playFocused" id="4:35"/>
        <ViewModelPropertyBoolean name="nextFocused" id="4:36"/>
        <ViewModelPropertyBoolean name="npVisible" id="4:37"/>
        <ViewModelPropertyNumber name="appsScroll" id="4:38"/>
        <ViewModelPropertyBoolean name="appsMoreBelow" id="4:39"/>
        <ViewModelPropertyBoolean name="themeFocused" id="4:40"/>
        <ViewModelInstance exports="true" name="Default" id="5:1">
            <ViewModelInstanceString propertyValue="11:11 PM" viewModelPropertyId="4:2"/>
            <ViewModelInstanceString propertyValue="Tuesday, November 17" viewModelPropertyId="4:3"/>
            <ViewModelInstanceString propertyValue="Slide" viewModelPropertyId="4:4"/>
            <ViewModelInstanceString propertyValue="The Meadow Band · Spotify" viewModelPropertyId="4:5"/>
            <ViewModelInstanceAssetImage propertyValue="6:2" viewModelPropertyId="4:6"/>
            <ViewModelInstanceBoolean propertyValue="true" viewModelPropertyId="4:7"/>
            <ViewModelInstanceBoolean propertyValue="false" viewModelPropertyId="4:30"/>
            <ViewModelInstanceBoolean propertyValue="false" viewModelPropertyId="4:31"/>
            <ViewModelInstanceBoolean propertyValue="false" viewModelPropertyId="4:34"/>
            <ViewModelInstanceBoolean propertyValue="false" viewModelPropertyId="4:35"/>
            <ViewModelInstanceBoolean propertyValue="false" viewModelPropertyId="4:36"/>
            <ViewModelInstanceBoolean propertyValue="true" viewModelPropertyId="4:37"/>
            <ViewModelInstanceNumber propertyValue="0" viewModelPropertyId="4:38"/>
            <ViewModelInstanceBoolean propertyValue="false" viewModelPropertyId="4:39"/>
            <ViewModelInstanceBoolean propertyValue="false" viewModelPropertyId="4:40"/>
            <ViewModelInstanceList viewModelPropertyId="4:8">''')
for iid in fav_ids:
    out.append(f'                <ViewModelInstanceListItem viewModelId="4:20" viewModelInstanceId="{iid}"/>')
out.append('            </ViewModelInstanceList>')
out.append('            <ViewModelInstanceList viewModelPropertyId="4:9">')
for iid in app_ids:
    out.append(f'                <ViewModelInstanceListItem viewModelId="4:10" viewModelInstanceId="{iid}"/>')
out.append('''            </ViewModelInstanceList>
        </ViewModelInstance>
    </ViewModel>
</Rive>''')

(theme / "data.rml").write_text("\n".join(out) + "\n")
print(f"wrote {theme / 'data.rml'}: {len(FAVS)} favourites, {len(APPS)} apps")
